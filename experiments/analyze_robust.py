#!/usr/bin/env python3
"""Tables and figure for the stress tests (offline results of experiments/robustness.py).

    python experiments/analyze_robust.py      ->  results/summary_robust.md, results/fig_robust.png
"""
import collections
import csv
import math
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES_DIR = os.path.join(ROOT, "results")


def rd(name):
    p = os.path.join(RES_DIR, name)
    return list(csv.DictReader(open(p))) if os.path.exists(p) else None


def wilson(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return 100 * max(0, (c - h) / d), 100 * min(1, (c + h) / d)


def agg(rows, key, fields):
    out = collections.defaultdict(collections.Counter)
    for r in rows:
        k = key(r)
        out[k]["n"] += 1
        for f in fields:
            if f in r:
                out[k][f] += int(r[f])
    return out


def cell(c, f):
    lo, hi = wilson(c[f], c["n"])
    return "%.1f (%.0f-%.0f)" % (100.0 * c[f] / c["n"], lo, hi)


def main():
    md = ["# Stress-test results (simulation; generated by experiments/analyze_robust.py)", ""]
    noise, loss, slow, pair, decoy = (rd("robustness_%s.csv" % n) for n in ("noise", "loss", "slow", "pair", "decoy"))
    if noise:
        a = agg(noise, lambda r: int(r["noise_events"]), ["engine", "engine_any", "rules"])
        md += ["## Noise: attack hidden among unrelated benign events", "", "| Unrelated events | trials | IAMWatch ACTIVE % (95% CI) | stateless rules % |", "|---|---|---|---|"]
        for k in sorted(a):
            md.append("| %d | %d | %s | %s |" % (k, a[k]["n"], cell(a[k], "engine"), cell(a[k], "rules")))
        md.append("")
    if loss:
        a = agg(loss, lambda r: float(r["loss"]), ["engine", "engine_any", "active_any", "engine_gf", "engine_any_gf", "rules"])
        md += ["## Lost events", "", "| Events lost | trials | ACTIVE, right origin | ACTIVE, any origin | ACTIVE or WATCH | with gap-fill (ACTIVE, right origin) | stateless rules |", "|---|---|---|---|---|---|---|"]
        for k in sorted(a):
            md.append("| %d%% | %d | %s | %s | %s | %s | %s |" % (round(100 * k), a[k]["n"], cell(a[k], "engine"), cell(a[k], "active_any"),
                                                               cell(a[k], "engine_any"), cell(a[k], "engine_gf"), cell(a[k], "rules")))
        md += ["", "'Any origin' counts an ACTIVE alert that blames the role session when the AssumeRole that issued its credential was lost: "
               "the privilege change is still caught, but the attacker is not named. Gap-fill assumes the event history returns the lost "
               "events (recall set by --gapfill-recall; validated on live AWS by experiments/live_gapfill.py).", ""]
    if slow:
        a = agg(slow, lambda r: (r["scenario"], int(r["gap_s"])), ["engine", "engine_any", "engine_lw", "engine_any_lw"])
        md += ["## Slow attacker: delay between the steps", "", "| Family | gap | trials | fixed 1 h window ACTIVE % | 12 h linked window ACTIVE % | any alert % (linked) |", "|---|---|---|---|---|---|"]
        for k in sorted(a, key=lambda k: (k[0], k[1])):
            md.append("| %s | %s | %d | %s | %s | %s |" % (k[0].upper(), ("%d s" % k[1]) if k[1] < 3600 else ("%.1f h" % (k[1] / 3600)), a[k]["n"],
                                                          cell(a[k], "engine"), cell(a[k], "engine_lw"), cell(a[k], "engine_any_lw")))
        md.append("")
    if pair:
        n = len(pair)
        k = sum(int(r["both"]) for r in pair)
        md += ["## Two simultaneous attackers", "", "Both attacks detected and attributed correctly in %d of %d trials (%.1f%%; 95%% CI %.0f-%.0f%%)." % ((k, n, 100.0 * k / n) + wilson(k, n)), ""]
    if decoy:
        d = collections.defaultdict(list)
        for r in decoy:
            d[round(int(r["events"]) / 1.6 / 100) * 100 if False else min((100, 500, 1000, 2000), key=lambda t: abs(int(r["events"]) / 1.6 - t))].append(r)
        md += ["## Benign-only load (simulated)", "", "| Workload steps | mean events | runs | ACTIVE alerts (total) | mean WATCH per run |", "|---|---|---|---|---|"]
        for t in sorted(d):
            rr = d[t]
            md.append("| %d | %.0f | %d | %d | %.1f |" % (t, sum(int(r["events"]) for r in rr) / len(rr), len(rr), sum(int(r["active"]) for r in rr),
                                                        sum(int(r["watch"]) for r in rr) / len(rr)))
        md.append("")
    open(os.path.join(RES_DIR, "summary_robust.md"), "w").write("\n".join(md))
    print("\n".join(md))

    if loss and slow:
        fig, ax = plt.subplots(1, 2, figsize=(9, 3.6), dpi=200)
        a = agg(loss, lambda r: float(r["loss"]), ["engine", "engine_any", "engine_gf", "rules"])
        ps = sorted(a)
        for f, col, lab in (("engine", "#1f77b4", "IAMWatch ACTIVE (right origin)"), ("engine_gf", "#2ca02c", "+ gap-fill"),
                            ("engine_any", "#ff7f0e", "ACTIVE or WATCH"), ("rules", "#7f7f7f", "Single-event rules")):
            x = [100 * p for p in ps]
            y = [100.0 * a[p][f] / a[p]["n"] for p in ps]
            ax[0].plot(x, y, marker="o", ms=4, color=col, label=lab)
            ax[0].fill_between(x, [wilson(a[p][f], a[p]["n"])[0] for p in ps], [wilson(a[p][f], a[p]["n"])[1] for p in ps], color=col, alpha=.12)
        ax[0].set_xlabel("events lost (%)")
        ax[0].set_ylabel("attacks detected (%)")
        ax[0].set_ylim(0, 105)
        ax[0].set_title("(a) Lost CloudTrail events", fontsize=10)
        ax[0].legend(fontsize=7, loc="lower left")
        ax[0].grid(alpha=.3)
        b = agg([r for r in slow if r["scenario"] in ("s1", "x1")], lambda r: int(r["gap_s"]), ["engine", "engine_lw", "engine_any"])
        gaps = sorted(b)
        xs = list(range(len(gaps)))
        ax[1].plot(xs, [100.0 * b[g]["engine"] / b[g]["n"] for g in gaps], marker="o", color="#d62728", label="fixed 1 h window")
        ax[1].plot(xs, [100.0 * b[g]["engine_lw"] / b[g]["n"] for g in gaps], marker="s", ms=4, color="#1f77b4", label="12 h linked window")
        ax[1].plot(xs, [100.0 * b[g]["engine_any"] / b[g]["n"] for g in gaps], ls="--", color="#555", label="any alert (fixed window)")
        ax[1].set_xticks(xs)
        ax[1].set_xticklabels([("%ds" % g) if g < 600 else ("%dm" % (g // 60)) if g < 3600 else ("%.0fh" % (g / 3600)) for g in gaps], fontsize=7)
        ax[1].set_xlabel("delay between the attack steps (S1 and X1 chains)")
        ax[1].set_ylim(-5, 110)
        ax[1].set_title("(b) Slow attacker", fontsize=10)
        ax[1].legend(fontsize=7, loc="lower left")
        ax[1].grid(alpha=.3)
        fig.tight_layout()
        fig.savefig(os.path.join(RES_DIR, "fig_robust.png"))


if __name__ == "__main__":
    main()
