#!/usr/bin/env python3
"""Turn the REAL-AWS experiment files into the tables and figures of the paper's results section.

    python experiments/analyze_live.py

Reads (whatever exists):  results/attacks_real.csv   results/guardduty_findings.json   results/benign_live.json
                          results/gapfill_real.csv   results/batch_scan.json
Writes:  results/summary_live.md   results/live_family_table.csv   results/fig_live_family.png
         results/fig_live_delay.png
"""
import csv
import json
import math
import os
import statistics as st
from datetime import datetime, timezone

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
FAM = ["s1", "s2", "s3", "s4", "s5", "x1", "x2", "x3", "x4"]


def wilson(k, n, z=1.96):
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return 100 * max(0, (c - h) / d), 100 * min(1, (c + h) / d)


def pct(k, n):
    lo, hi = wilson(k, n)
    return "%d/%d (%.0f%%; 95%% CI %.0f-%.0f%%)" % (k, n, 100.0 * k / n if n else 0, lo, hi)


def t(s):
    return datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc).timestamp()


def ts(s):
    if not s:
        return None
    return datetime.fromisoformat(str(s).replace("Z", "+00:00")).timestamp()


def q(vals, p):
    v = sorted(vals)
    if not v:
        return float("nan")
    i = (len(v) - 1) * p
    lo, hi = int(math.floor(i)), int(math.ceil(i))
    return v[lo] + (v[hi] - v[lo]) * (i - lo)


def load(name):
    path = os.path.join(RES, name)
    return list(csv.DictReader(open(path))) if os.path.exists(path) else None


def main():
    rows = load("attacks_real.csv")
    if not rows:
        raise SystemExit("results/attacks_real.csv not found - run experiments/run_attacks.py first")
    gd = None
    gpath = os.path.join(RES, "guardduty_findings.json")
    if os.path.exists(gpath):
        gd = json.load(open(gpath))
    md = ["# Live AWS results (generated by experiments/analyze_live.py)", ""]
    by = {k: [r for r in rows if r["scenario"] == k] for k in FAM}
    n_all = len(rows)
    det_all = sum(int(r["detected"]) for r in rows)
    rules_all = sum(int(r["rules_detected"]) for r in rows)

    # ---- GuardDuty matching
    def gd_hit(r, strict):
        if gd is None:
            return None
        a, b = t(r["attack_start"]) - 5, (t(r["attack_end"]) if r.get("attack_end") else t(r["attack_start"]) + 60) + 60
        for f in gd:
            f1, f2 = ts(f.get("first_seen")) or ts(f.get("created")), ts(f.get("last_seen")) or ts(f.get("created"))
            if f1 is None or f2 is None or f2 < a or f1 > b:
                continue
            if strict and (f.get("user_name") or "") != r["origin"]:
                continue
            return True
        return False

    md += ["## Table L1 - detection per attack family (real AWS account)", "",
           "| Family | Attacks | IAMWatch ACTIVE, right origin | Single-event rules (R1-R5) | GuardDuty, any finding in window | GuardDuty, finding names the origin |",
           "|---|---|---|---|---|---|"]
    csv_rows = []
    for k in FAM:
        rs = by[k]
        if not rs:
            continue
        n = len(rs)
        d = sum(int(r["detected"]) for r in rs)
        ru = sum(int(r["rules_detected"]) for r in rs)
        g1 = sum(1 for r in rs if gd_hit(r, False)) if gd is not None else None
        g2 = sum(1 for r in rs if gd_hit(r, True)) if gd is not None else None
        md.append("| %s | %d | %s | %s | %s | %s |" % (k.upper(), n, pct(d, n), pct(ru, n),
                                                       pct(g1, n) if g1 is not None else "n/a",
                                                       pct(g2, n) if g2 is not None else "n/a"))
        csv_rows.append([k, n, d, ru, g1, g2])
    g1_all = sum(1 for r in rows if gd_hit(r, False)) if gd is not None else None
    g2_all = sum(1 for r in rows if gd_hit(r, True)) if gd is not None else None
    md.append("| **All** | %d | **%s** | %s | %s | %s |" % (n_all, pct(det_all, n_all), pct(rules_all, n_all),
                                                           pct(g1_all, n_all) if g1_all is not None else "n/a",
                                                           pct(g2_all, n_all) if g2_all is not None else "n/a"))
    md += ["", "Rule hits are computed offline from the same raw CloudTrail events that the stack received; GuardDuty "
           "findings are matched to an attack when their event window overlaps the attack (\"any finding\" is the "
           "generous reading) and, in the last column, when the finding names the attacking user. "
           "Rules never name the origin of a chain.", ""]
    with open(os.path.join(RES, "live_family_table.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["family", "attacks", "iamwatch_detected", "rules_detected", "guardduty_any", "guardduty_origin"])
        w.writerows(csv_rows)

    # ---- delay
    det = [r for r in rows if int(r["detected"])]
    tot = [float(r["total_s"]) for r in det if r.get("total_s") not in ("", None)]
    md += ["## Table L2 - delay from the last CloudTrail event of the attack to the stored alert (seconds)", "",
           "| Family | n | median | p95 | max | median CloudTrail->queue | median queue | median processing |", "|---|---|---|---|---|---|---|---|"]

    def stage(rs, col):
        v = [float(r[col]) for r in rs if r.get(col) not in ("", None)]
        return "%.2f" % st.median(v) if v else "n/a"

    for k in FAM + ["all"]:
        rs = det if k == "all" else [r for r in det if r["scenario"] == k]
        v = [float(r["total_s"]) for r in rs if r.get("total_s") not in ("", None)]
        if not v:
            continue
        md.append("| %s | %d | %.1f | %.1f | %.1f | %s | %s | %s |" % (k.upper() if k != "all" else "**All**", len(v), st.median(v), q(v, .95), max(v),
                                                                       stage(rs, "delivery_s"), stage(rs, "queue_s"), stage(rs, "processing_s")))
    md.append("")
    if os.path.exists(os.path.join(RES, "batch_scan.json")):
        b = json.load(open(os.path.join(RES, "batch_scan.json")))
        md += ["A full IAM download plus graph build took %.1f s here (download %.1f s, build %.2f s), so a periodic scan "
               "adds that time plus on average half its interval to every detection." % (b["runtime_s"], b["download_s"], b["build_s"]), ""]

    # ---- benign
    bpath = os.path.join(RES, "benign_live.json")
    if os.path.exists(bpath):
        b = json.load(open(bpath))
        md += ["## Table L3 - real benign activity", "",
               "| Operations | Minutes | CloudTrail events seen | IAMWatch ACTIVE (false alerts) | IAMWatch WATCH | EVASION | Single-event rule hits |",
               "|---|---|---|---|---|---|---|",
               "| %d | %.0f | %d | **%d** | %d | %d | %d |" % (b["operations"], b["minutes"], b["events_seen"], b["iamwatch_active"],
                                                                 b["iamwatch_watch"], b["iamwatch_evasion"], b["stateless_rule_hits"]), ""]
        if b["active_alerts"]:
            md += ["ACTIVE alerts raised on benign activity (investigate each one):", ""] + ["- %s: %s" % (a["origin"], a["path"]) for a in b["active_alerts"]] + [""]

    # ---- gap fill
    g = load("gapfill_real.csv")
    if g:
        md += ["## Table L4 - attacks whose events never reached the queue (gap-fill recovery)", "",
               "| Family | Attacks | Detected after recovery | Median seconds after last event | Max |", "|---|---|---|---|---|"]
        for k in FAM:
            rs = [r for r in g if r["scenario"] == k]
            if not rs:
                continue
            v = [float(r["seconds_after_last_event"]) for r in rs if r.get("seconds_after_last_event")]
            md.append("| %s | %d | %s | %s | %s |" % (k.upper(), len(rs), pct(sum(int(r["detected"]) for r in rs), len(rs)),
                                                      "%.0f" % st.median(v) if v else "n/a", "%.0f" % max(v) if v else "n/a"))
        md.append("")

    open(os.path.join(RES, "summary_live.md"), "w").write("\n".join(md))
    print("\n".join(md))

    # ---- figures
    fig, ax = plt.subplots(figsize=(7.5, 3.6))
    ks = [k for k in FAM if by[k]]
    xs = range(len(ks))
    w = 0.27

    def bar(offset, vals, label, color):
        lo = [max(0, v[0] - v[1]) for v in vals]
        hi = [max(0, v[2] - v[0]) for v in vals]
        ax.bar([x + offset for x in xs], [v[0] for v in vals], w, yerr=[lo, hi], capsize=2, label=label, color=color)

    iw = [(100.0 * sum(int(r["detected"]) for r in by[k]) / len(by[k]),) + wilson(sum(int(r["detected"]) for r in by[k]), len(by[k])) for k in ks]
    ru = [(100.0 * sum(int(r["rules_detected"]) for r in by[k]) / len(by[k]),) + wilson(sum(int(r["rules_detected"]) for r in by[k]), len(by[k])) for k in ks]
    bar(-w, iw, "IAMWatch (ACTIVE, right origin)", "#1f77b4")
    bar(0, ru, "Single-event rules", "#ff7f0e")
    if gd is not None:
        gv = []
        for k in ks:
            n = len(by[k])
            c = sum(1 for r in by[k] if gd_hit(r, False))
            gv.append((100.0 * c / n,) + wilson(c, n))
        bar(w, gv, "GuardDuty (any finding)", "#2ca02c")
    ax.set_xticks(list(xs))
    ax.set_xticklabels([k.upper() for k in ks])
    ax.set_ylabel("attacks detected (%)")
    ax.set_ylim(0, 108)
    ax.legend(fontsize=7, loc="lower left")
    ax.set_title("Live AWS: detection per attack family (95% Wilson intervals)", fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(RES, "fig_live_family.png"), dpi=200)
    plt.close(fig)
    if tot:
        fig, ax = plt.subplots(figsize=(5, 3.2))
        v = sorted(tot)
        ax.step(v, [100.0 * (i + 1) / len(v) for i in range(len(v))], where="post")
        ax.set_xlabel("seconds from last CloudTrail event to stored alert")
        ax.set_ylabel("attacks (%)")
        ax.set_title("Live detection delay (n=%d)" % len(v), fontsize=9)
        ax.grid(alpha=.3)
        fig.tight_layout()
        fig.savefig(os.path.join(RES, "fig_live_delay.png"), dpi=200)


if __name__ == "__main__":
    main()
